package io.ogwars.cloud.controller.runtime

import io.ogwars.cloud.controller.kube.PodSpecBuilder
import io.ogwars.cloud.domain.runtime.RuntimeProfiles

/**
 * Config files the controller writes into bundles. Keys left out keep their platform defaults; the OgCloud plugins
 * set everything dynamic (servers, MOTD, protocol per backend) at runtime.
 */
object GeneratedConfigs {
    /**
     * Velocity 4.3.0's config format. The Velocity image's entrypoint writes the last mounted forwarding token to
     * [FORWARDING_SECRET_FILE] (T-0508), which is the token proxies use (D-0065, D-0078).
     */
    fun velocityToml(): String =
        """
        |# Generated by the OgCloud controller; changes are overwritten.
        |config-version = "$VELOCITY_CONFIG_VERSION"
        |bind = "0.0.0.0:${PodSpecBuilder.MINECRAFT_PORT}"
        |online-mode = true
        |force-key-authentication = true
        |player-info-forwarding-mode = "${RuntimeProfiles.FORWARDING}"
        |forwarding-secret-file = "$FORWARDING_SECRET_FILE"
        |announce-forge = false
        |kick-existing-players = false
        |
        |[servers]
        |try = []
        |
        |[forced-hosts]
        |
        |[advanced]
        |# The load balancer sends PROXY protocol v2 headers with the real client address.
        |haproxy-protocol = true
        |log-player-connections = true
        |accepts-transfers = false
        |
        """.trimMargin()

    /** Blocks clients below the catalog's range; the Velocity plugin registers each backend's protocol (T-0504). */
    fun viaVersionConfig(): String =
        """
        |# Generated by the OgCloud controller; changes are overwritten.
        |checkforupdates: false
        |block-protocols: ["<${RuntimeProfiles.MIN_CLIENT_PROTOCOL}"]
        |block-disconnect-msg: "Please join with Minecraft 1.8 or newer."
        |velocity-servers: {}
        |
        """.trimMargin()

    /** Matches Velocity 4.3.0 (profile velocity-4.3.0); a newer config version means a new generated file. */
    private const val VELOCITY_CONFIG_VERSION = "2.9"
    const val FORWARDING_SECRET_FILE = "/tmp/ogcloud/forwarding.secret"
}
