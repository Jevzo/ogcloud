// Package constants renders a list of named strings shared by the control plane and the data plane, such as
// pod labels, for Go and Kotlin from one contract file.
package constants

import (
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"strings"

	"github.com/jevzo/ogcloud/data-plane/pkg/contracts/naming"

	"github.com/jevzo/ogcloud/data-plane/pkg/strictyaml"
)

// Catalog is a Kotlin object's worth of constants.
type Catalog struct {
	Object    string     `yaml:"object"`
	Doc       string     `yaml:"doc"`
	Constants []Constant `yaml:"constants"`
}

// Constant is a named string.
type Constant struct {
	Name  string `yaml:"name"`
	Value string `yaml:"value"`
	Doc   string `yaml:"doc"`
}

var (
	objectPattern = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)
	namePattern   = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
)

// Parse decodes a constants contract, rejecting unknown fields.
func Parse(data []byte) (*Catalog, error) {
	var catalog Catalog
	if err := strictyaml.Decode(data, &catalog); err != nil {
		return nil, err
	}
	return &catalog, nil
}

// Validate checks names and values.
func (c *Catalog) Validate() error {
	var problems []error
	if !objectPattern.MatchString(c.Object) {
		problems = append(problems, fmt.Errorf("object %q is not a PascalCase name", c.Object))
	}
	seen := map[string]bool{}
	for _, constant := range c.Constants {
		if !namePattern.MatchString(constant.Name) || seen[constant.Name] {
			problems = append(problems, fmt.Errorf("constant %q is not a unique lowerCamelCase name", constant.Name))
		}
		if constant.Value == "" {
			problems = append(problems, fmt.Errorf("constant %s has no value", constant.Name))
		}
		seen[constant.Name] = true
	}
	return errors.Join(problems...)
}

// RenderGo writes the constants as an exported Go const block.
func RenderGo(packageName, source string, c *Catalog) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by ogcloud codegen from %s. DO NOT EDIT.\n\n", source)
	fmt.Fprintf(&b, "// Package %s holds the %s: %s\npackage %s\n\nconst (\n", packageName, c.Object, c.Doc, packageName)
	for _, constant := range c.Constants {
		if constant.Doc != "" {
			fmt.Fprintf(&b, "\t// %s %s\n", naming.Pascal(constant.Name), constant.Doc)
		}
		fmt.Fprintf(&b, "\t%s = %q\n", naming.Pascal(constant.Name), constant.Value)
	}
	b.WriteString(")\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

// RenderKotlin writes the constants as a Kotlin object.
func RenderKotlin(packageName, source string, c *Catalog) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by ogcloud codegen from %s. DO NOT EDIT.\npackage %s\n\n", source, packageName)
	fmt.Fprintf(&b, "/** %s */\nobject %s {\n", c.Doc, c.Object)
	for _, constant := range c.Constants {
		if constant.Doc != "" {
			fmt.Fprintf(&b, "    /** %s */\n", constant.Doc)
		}
		fmt.Fprintf(&b, "    const val %s = %q\n", naming.UpperSnake(constant.Name), constant.Value)
	}
	b.WriteString("}\n")
	return []byte(b.String())
}
