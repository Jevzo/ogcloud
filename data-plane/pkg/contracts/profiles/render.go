package profiles

import (
	"fmt"
	"go/format"
	"strings"
)

const generatedHeader = "Code generated by ogcloud codegen from contracts/runtime-profiles.yaml. DO NOT EDIT."

// RenderGo writes the data half of package runtimeprofiles; its types are hand-written.
func RenderGo(c Catalog) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage runtimeprofiles\n\n", generatedHeader)
	fmt.Fprintf(&b, "// Forwarding is the network-wide player-info forwarding mode (D-0065).\nconst Forwarding = %q\n\n", c.Forwarding)
	fmt.Fprintf(&b, "// Client protocol range the network admits.\nconst (\n\tMinClientProtocol = %d\n\tMaxClientProtocol = %d\n)\n\n",
		c.ClientProtocols.Min, c.ClientProtocols.Max)
	b.WriteString("// All returns every runtime profile in catalog order.\nfunc All() []Profile {\n\treturn []Profile{\n")
	for _, p := range c.Profiles {
		info := platforms[p.Platform]
		fmt.Fprintf(&b, "\t\t{ID: %q, Platform: %s, Role: Role%s, Version: %q, Protocol: %d, JavaVersion: %d},\n",
			p.ID, info.goConst, title(info.role), p.Version, p.Protocol, p.JavaVersion)
	}
	b.WriteString("\t}\n}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

// RenderKotlin writes an object holding the catalog for the domain module's RuntimeProfile type.
func RenderKotlin(packageName string, c Catalog) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\npackage %s\n\nobject RuntimeProfiles {\n", generatedHeader, packageName)
	fmt.Fprintf(&b, "    const val FORWARDING = %q\n    const val MIN_CLIENT_PROTOCOL = %d\n    const val MAX_CLIENT_PROTOCOL = %d\n\n",
		c.Forwarding, c.ClientProtocols.Min, c.ClientProtocols.Max)
	b.WriteString("    val ALL: List<RuntimeProfile> =\n        listOf(\n")
	for _, p := range c.Profiles {
		info := platforms[p.Platform]
		fmt.Fprintf(&b, "            RuntimeProfile(%q, Platform.%s, ProfileRole.%s, %q, %d, %d),\n",
			p.ID, info.kotlinEnum, strings.ToUpper(info.role), p.Version, p.Protocol, p.JavaVersion)
	}
	b.WriteString("        )\n")
	if len(c.Plugins) > 0 {
		b.WriteString("\n    val PLUGINS: List<RuntimePlugin> =\n        listOf(\n")
		for _, p := range c.Plugins {
			enums := make([]string, 0, len(p.Platforms))
			for _, name := range p.Platforms {
				enums = append(enums, "Platform."+platforms[name].kotlinEnum)
			}
			fmt.Fprintf(&b, "            RuntimePlugin(\n                %q,\n                setOf(%s),\n                %q,\n                %q,\n                %q,\n                %q,\n            ),\n",
				p.ID, strings.Join(enums, ", "), p.File, p.Version, p.URL, p.SHA512)
		}
		b.WriteString("        )\n")
	} else {
		b.WriteString("\n    val PLUGINS: List<RuntimePlugin> = emptyList()\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func title(s string) string {
	return strings.ToUpper(s[:1]) + s[1:]
}
