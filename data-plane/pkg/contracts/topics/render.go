package topics

import (
	"fmt"
	"go/format"
	"slices"
	"strings"
)

const (
	namePrefix      = "ogcloud."
	generatedHeader = "Code generated by ogcloud codegen from contracts/kafka/topics.yaml. DO NOT EDIT."
)

// RenderGo writes Go constants for every topic name.
func RenderGo(packageName string, topics []Topic) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage %s\n\nconst (\n", generatedHeader, packageName)
	for _, topic := range topics {
		fmt.Fprintf(&b, "\t%s = %q\n", goIdentifier(topic.Name), topic.Name)
	}
	b.WriteString(")\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

// RenderKotlin writes a Kotlin object holding every topic name.
func RenderKotlin(packageName string, topics []Topic) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\npackage %s\n\nobject KafkaTopics {\n", generatedHeader, packageName)
	for _, topic := range topics {
		fmt.Fprintf(&b, "    const val %s = %q\n", kotlinIdentifier(topic.Name), topic.Name)
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

// RenderStrimzi writes a Helm template with one KafkaTopic per topic and one KafkaUser per
// service, whose ACLs allow exactly the topics it produces to or consumes from.
func RenderStrimzi(topics []Topic) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", generatedHeader)
	for _, topic := range topics {
		fmt.Fprintf(&b, `---
apiVersion: kafka.strimzi.io/v1
kind: KafkaTopic
metadata:
  name: %s
  labels:
    strimzi.io/cluster: {{ .Values.kafka.clusterName }}
spec:
  topicName: %s
  partitions: %d
  replicas: {{ .Values.kafka.replicationFactor }}
  config:
    retention.ms: "%d"
`, topic.Name, topic.Name, topic.Partitions, topic.Retention.Milliseconds())
	}
	for _, service := range services(topics) {
		writeUser(&b, service, topics)
	}
	return []byte(b.String())
}

func writeUser(b *strings.Builder, service string, topics []Topic) {
	fmt.Fprintf(b, `---
apiVersion: kafka.strimzi.io/v1
kind: KafkaUser
metadata:
  name: ogcloud-%[1]s
  labels:
    strimzi.io/cluster: {{ .Values.kafka.clusterName }}
spec:
  authentication:
    type: scram-sha-512
    password:
      valueFrom:
        secretKeyRef:
          name: ogcloud-kafka-%[1]s
          key: password
  authorization:
    type: simple
    acls:
`, service)
	for _, topic := range topics {
		if slices.Contains(topic.Producers, service) {
			writeACL(b, "topic", topic.Name, "literal", "Write", "Describe")
		}
		if slices.Contains(topic.Consumers, service) {
			writeACL(b, "topic", topic.Name, "literal", "Read", "Describe")
		}
	}
	if consumesAny(service, topics) {
		// Prefix match: replicas use per-pod groups (ogcloud-<service>-<pod>) for broadcast topics.
		writeACL(b, "group", "ogcloud-"+service, "prefix", "Read")
	}
}

func writeACL(b *strings.Builder, resourceType, name, pattern string, operations ...string) {
	fmt.Fprintf(b, `      - resource:
          type: %s
          name: %s
          patternType: %s
        operations: [%s]
`, resourceType, name, pattern, strings.Join(operations, ", "))
}

func services(topics []Topic) []string {
	var all []string
	for _, topic := range topics {
		all = append(all, topic.Producers...)
		all = append(all, topic.Consumers...)
	}
	slices.Sort(all)
	return slices.Compact(all)
}

func consumesAny(service string, topics []Topic) bool {
	return slices.ContainsFunc(topics, func(t Topic) bool { return slices.Contains(t.Consumers, service) })
}

func nameParts(name string) []string {
	return strings.FieldsFunc(strings.TrimPrefix(name, namePrefix), func(r rune) bool { return r == '.' || r == '-' })
}

func goIdentifier(name string) string {
	var b strings.Builder
	for _, part := range nameParts(name) {
		if "."+part == deadLetterSuffix {
			b.WriteString(strings.ToUpper(part))
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func kotlinIdentifier(name string) string {
	return strings.ToUpper(strings.Join(nameParts(name), "_"))
}
