const generatedHeader = "Code generated by ogcloud codegen from contracts/livestate/keys.yaml. DO NOT EDIT."

// RenderGo writes the key layout as Go constants and functions; ids and group ids are plain strings.
func RenderGo(packageName string, c *Catalog) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\n// Package %s is the Valkey key layout shared with the control plane (D-0111).\npackage %s\n\n", generatedHeader, packageName, packageName)
	b.WriteString("import (\n")
	if c.usesLowercase() {
		b.WriteString("\t\"strings\"\n")
	}
	if len(c.TTLs) > 0 {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "// Hash fields of revisioned records.\nconst (\n\tFieldRevision = %q\n\tFieldData = %q\n)\n\n", c.Fields.Revision, c.Fields.Data)
	b.WriteString("const (\n")
	for _, ttl := range c.TTLs {
		duration, err := ttl.Parsed()
		if err != nil {
			return nil, err
		}
		writeGoDoc(&b, "\t", ttl.Doc)
		fmt.Fprintf(&b, "\t%sTTL = %s\n", pascal(ttl.Name), goDuration(duration))
	}
	b.WriteString(")\n\nconst (\n")
	for _, constant := range c.Constants {
		writeGoDoc(&b, "\t", constant.Doc)
		fmt.Fprintf(&b, "\t%s = %q\n", pascal(constant.Name), constant.Value)
	}
	b.WriteString(")\n\n")
	writeGoKinds(&b, "ReadModelKind", "ReadModel", "names a family of read models.", c.ReadModelKinds)
	writeGoKinds(&b, "OneTimeKind", "OneTime", "names what a one-time value is for.", c.OneTimeKinds)
	for _, key := range c.Keys {
		segments, err := key.Segments()
		if err != nil {
			return nil, err
		}
		writeGoKey(&b, key, segments)
	}
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

func writeGoKinds(b *strings.Builder, typeName, prefix, doc string, kinds []Kind) {
	fmt.Fprintf(b, "// %s %s\ntype %s string\n\nconst (\n", typeName, doc, typeName)
	for _, kind := range kinds {
		writeGoDoc(b, "\t", kind.Doc)
		fmt.Fprintf(b, "\t%s%s %s = %q\n", prefix, pascal(kind.Name), typeName, kind.Key)
	}
	b.WriteString(")\n\n")
}

func writeGoKey(b *strings.Builder, key Key, segments []Segment) {
	name := pascal(key.Name)
	if len(segments) == 1 && segments[0].Param == nil {
		writeGoDoc(b, "", key.Doc)
		fmt.Fprintf(b, "const %s = %q\n\n", name, segments[0].Literal)
		return
	}
	if key.Prefix {
		fmt.Fprintf(b, "// %sPrefix starts every %s key.\nconst %sPrefix = %q\n\n", name, name, name, segments[0].Literal)
	}
	var params, parts []string
	for _, segment := range segments {
		if segment.Param == nil {
			parts = append(parts, fmt.Sprintf("%q", segment.Literal))
			continue
		}
		param := segment.Param
		params = append(params, param.Name+" "+goParamType(param.Type))
		switch param.Type {
		case ParamLowercase:
			parts = append(parts, "strings.ToLower("+param.Name+")")
		case ParamReadModelKind, ParamOneTimeKind:
			parts = append(parts, "string("+param.Name+")")
		default:
			parts = append(parts, param.Name)
		}
	}
	fmt.Fprintf(b, "// %s returns the key %s.", name, key.Pattern)
	if key.Doc != "" {
		fmt.Fprintf(b, " %s", key.Doc)
	}
	fmt.Fprintf(b, "\nfunc %s(%s) string {\n\treturn %s\n}\n\n", name, strings.Join(params, ", "), strings.Join(parts, " + "))
}

func goParamType(t ParamType) string {
	switch t {
	case ParamReadModelKind:
		return "ReadModelKind"
	case ParamOneTimeKind:
		return "OneTimeKind"
	default:
		return "string"
	}
}

func goDuration(d time.Duration) string {
	switch {
	case d%time.Hour == 0:
		return fmt.Sprintf("%d * time.Hour", d/time.Hour)
	case d%time.Minute == 0:
		return fmt.Sprintf("%d * time.Minute", d/time.Minute)
	default:
		return fmt.Sprintf("%d * time.Second", d/time.Second)
	}
}

func writeGoDoc(b *strings.Builder, indent, doc string) {
	if doc != "" {
		fmt.Fprintf(b, "%s// %s\n", indent, doc)
	}
}

// RenderKotlin writes the ValkeyKeys object for the livestate module.
func RenderKotlin(packageName string, c *Catalog) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\npackage %s\n\n", generatedHeader, packageName)
	imports := []string{}
	if c.usesType(ParamGroup) {
		imports = append(imports, "io.ogwars.cloud.domain.group.GroupId")
	}
	if c.usesType(ParamOneTimeKind) {
		imports = append(imports, "io.ogwars.cloud.domain.store.OneTimeKind")
	}
	if c.usesType(ParamReadModelKind) {
		imports = append(imports, "io.ogwars.cloud.domain.store.ReadModelKind")
	}
	if len(c.TTLs) > 0 {
		imports = append(imports, "java.time.Duration")
	}
	if c.usesType(ParamUUID) {
		imports = append(imports, "java.util.UUID")
	}
	for _, imp := range imports {
		fmt.Fprintf(&b, "import %s\n", imp)
	}
	b.WriteString("\n/** The Valkey key layout (D-0111), shared with the Go data plane. */\nobject ValkeyKeys {\n")
	fmt.Fprintf(&b, "    const val FIELD_REVISION = %q\n    const val FIELD_DATA = %q\n", c.Fields.Revision, c.Fields.Data)
	for _, ttl := range c.TTLs {
		duration, err := ttl.Parsed()
		if err != nil {
			return nil, err
		}
		writeKotlinDoc(&b, ttl.Doc)
		fmt.Fprintf(&b, "    val %s_TTL: Duration = %s\n", upperSnake(ttl.Name), kotlinDuration(duration))
	}
	for _, constant := range c.Constants {
		writeKotlinDoc(&b, constant.Doc)
		fmt.Fprintf(&b, "    const val %s = %q\n", upperSnake(constant.Name), constant.Value)
	}
	for _, key := range c.Keys {
		segments, err := key.Segments()
		if err != nil {
			return nil, err
		}
		writeKotlinKey(&b, key, segments)
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func writeKotlinKey(b *strings.Builder, key Key, segments []Segment) {
	writeKotlinDoc(b, key.Doc)
	if len(segments) == 1 && segments[0].Param == nil {
		fmt.Fprintf(b, "    const val %s = %q\n", upperSnake(key.Name), segments[0].Literal)
		return
	}
	if key.Prefix {
		fmt.Fprintf(b, "    const val %s_PREFIX = %q\n", upperSnake(key.Name), segments[0].Literal)
	}
	var params []string
	var template strings.Builder
	for _, segment := range segments {
		if segment.Param == nil {
			template.WriteString(strings.ReplaceAll(segment.Literal, "$", "\\$"))
			continue
		}
		param := segment.Param
		params = append(params, param.Name+": "+kotlinParamType(param.Type))
		switch param.Type {
		case ParamLowercase:
			template.WriteString("${" + param.Name + ".lowercase()}")
		case ParamReadModelKind, ParamOneTimeKind:
			template.WriteString("${" + param.Name + ".key}")
		default:
			template.WriteString("${" + param.Name + "}")
		}
	}
	fmt.Fprintf(b, "    fun %s(%s) = \"%s\"\n", key.Name, strings.Join(params, ", "), template.String())
}

func kotlinParamType(t ParamType) string {
	switch t {
	case ParamUUID:
		return "UUID"
	case ParamGroup:
		return "GroupId"
	case ParamReadModelKind:
		return "ReadModelKind"
	case ParamOneTimeKind:
		return "OneTimeKind"
	default:
		return "String"
	}
}

func kotlinDuration(d time.Duration) string {
	switch {
	case d%time.Hour == 0:
		return fmt.Sprintf("Duration.ofHours(%d)", d/time.Hour)
	case d%time.Minute == 0:
		return fmt.Sprintf("Duration.ofMinutes(%d)", d/time.Minute)
	default:
		return fmt.Sprintf("Duration.ofSeconds(%d)", d/time.Second)
	}
}

// RenderKotlinKinds writes the ReadModelKind and OneTimeKind enums for the domain module.
func RenderKotlinKinds(packageName string, c *Catalog) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\npackage %s\n\n", generatedHeader, packageName)
	writeKotlinEnum(&b, "ReadModelKind", "A family of read models; its key names them in Valkey (D-0077).", c.ReadModelKinds)
	b.WriteString("\n")
	writeKotlinEnum(&b, "OneTimeKind", "What a one-time value is for; it namespaces the keys.", c.OneTimeKinds)
	return []byte(b.String())
}

func writeKotlinEnum(b *strings.Builder, name, doc string, kinds []Kind) {
	fmt.Fprintf(b, "/** %s */\nenum class %s(\n    val key: String,\n) {\n", doc, name)
	for _, kind := range kinds {
		writeKotlinDoc(b, kind.Doc)
		fmt.Fprintf(b, "    %s(%q),\n", upperSnake(kind.Name), kind.Key)
	}
	b.WriteString("}\n")
}

func writeKotlinDoc(b *strings.Builder, doc string) {
	if doc != "" {
		fmt.Fprintf(b, "    /** %s */\n", doc)
	}
}

func (c *Catalog) usesType(t ParamType) bool {
	for _, key := range c.Keys {
		segments, err := key.Segments()
		if err != nil {
			continue
		}
		for _, segment := range segments {
			if segment.Param != nil && segment.Param.Type == t {
				return true
			}
		}
	}
	return false
}

func (c *Catalog) usesLowercase() bool { return c.usesType(ParamLowercase) }

func pascal(name string) string {
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

func upperSnake(name string) string {
	var b strings.Builder
	for i, r := range name {
		if unicode.IsUpper(r) && i > 0 {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}
